symbols_() {
    # รวมสัญลักษณ์และจัดกลุ่มละ 10 ตัว เว้นวรรค 2 spaces
    local type=""

    # กลุ่มเส้นตรงและวงเล็บ (Brackets & Lines)
    type+="\n∥  ‖  ⟬  ⟭  ⟦  ⟧  |  ¦  ‖  !\n"
    type+="‼  İ  ɭ  l  Ţ  ⌈  ⌉  ⌊  ⌋  —\n"

    # กลุ่มลูกศร (Arrows)
    type+="\n↿  ↾  ⇣  ⇡  ⇩  ⇧  ⇦  ⇨  ⇫  ⇮\n"
    type+="⇬  ⇯  ↖  ↗  ↙  ↘  ←  →  ↑  ↓\n"

    # กลุ่มสี่เหลี่ยมและรูปทรงเหลี่ยม (Squares & Polygons)
    type+="\n▢  ▥  ▨  ▬  ▭  ▣  ▦  ▩  ▮  ▯\n"
    type+="▤  ▧  ◊  ▪  ▫  ▴  ▵  ◂  ▸  ◃\n"
    type+="▹  ◆  ◇  ◈  ▱  ▰  ∎\n"

    # กลุ่มวงกลมและจุด (Circles & Dots)
    type+="\n◌  ●  ◙  ▼  ▽  ○  ◓  ◍  ◚  ◪\n"
    type+="•  ⁕  ‣  ⁴  ∏  ∐\n"

    printf '%b\n' "$type"
}
